# Usage: python3 -I scripts/make-tool-icons.py
# Reads scripts/tools.json and the logo library in library/logos (see its README for sources and licences)
# and writes site/vendor/tool-icons.js with just the logos the site can name.
import json, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lib = os.path.join(root, 'library', 'logos')
cfg = json.load(open(os.path.join(root, 'scripts', 'tools.json')))
tools = {k.lower(): v for k, v in cfg['tools'].items()}
models = {k.lower(): v for k, v in cfg['models'].items()}
icons, missing = {}, []
for slug in sorted({v for v in list(tools.values()) + list(models.values()) if v}):
    path = os.path.join(lib, slug + '.svg')
    if not os.path.exists(path):
        missing.append(slug); continue
    svg = open(path).read()
    head = re.match(r'<svg([^>]*)>', svg).group(1)
    inner = re.sub(r'<title>.*?</title>', '', svg[svg.index('>') + 1: svg.rindex('</svg>')])
    vb = re.search(r'viewBox="([^"]+)"', head).group(1)
    icons[slug] = [vb, inner, 1 if 'evenodd' in head else 0]
if missing:
    raise SystemExit('missing from library/logos: ' + ', '.join(missing))
out = {'tools': tools, 'models': models, 'icons': icons}
with open(os.path.join(root, 'site', 'vendor', 'tool-icons.js'), 'w') as f:
    f.write('// Generated by scripts/make-tool-icons.py from library/logos (LobeHub Icons, MIT; Simple Icons, CC0). Do not edit by hand.\n')
    f.write('window.TOOL_ICONS = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
print('tool icons:', len(icons), 'logos for', len(tools), 'tools and', len(models), 'model words')
