# Usage: python3 -I scripts/make-tool-icons.py /path/to/simple-icons/package
# Reads scripts/tools.json and the Simple Icons SVG files (CC0, simpleicons.org),
# and writes site/vendor/tool-icons.js with just the paths we use. Data only, no code from the package runs.
import json, os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pkg = sys.argv[1]
tools = {k: v for k, v in json.load(open(os.path.join(root, 'scripts', 'tools.json'))).items() if not k.startswith('_')}
icons = {}
for slug in sorted({v for v in tools.values() if v}):
    svg = open(os.path.join(pkg, 'icons', slug + '.svg')).read()
    icons[slug] = re.search(r'<path d="([^"]+)"', svg).group(1)
out = {'tools': {k.lower(): v for k, v in tools.items()}, 'paths': icons}
with open(os.path.join(root, 'site', 'vendor', 'tool-icons.js'), 'w') as f:
    f.write('// Generated by scripts/make-tool-icons.py from Simple Icons (CC0 1.0, simpleicons.org). Do not edit by hand.\n')
    f.write('window.TOOL_ICONS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('tool icons:', len(icons), 'logos for', len(tools), 'names')
