// Usage: node scripts/build-site.js
// Builds the website into dist/, ready to push to the site repo (Vercel deploys it from there).
//   site/*            the page, config and vercel.json
//   system/...        the fonts and the mark the page uses
//   posters/NN/       poster.jpg and thumb.jpg for each day
//   data/posters.js   the wall and the latest poster
//   feed.xml          RSS. Buttondown reads it to email subscribers; anyone can follow it in a reader
//   index.html        share preview tags (og:image etc.) pointing at the latest poster
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.resolve(__dirname, '..'), dist = path.join(root, 'dist');
const cp = (from, to) => { fs.mkdirSync(path.dirname(path.join(dist, to)), { recursive: true }); fs.cpSync(path.join(root, from), path.join(dist, to), { recursive: true }); };
fs.rmSync(dist, { recursive: true, force: true }); fs.mkdirSync(dist);
for (const f of fs.readdirSync(path.join(root, 'site'))) cp('site/' + f, f);
cp('system/assets/fonts', 'system/assets/fonts');
cp('system/assets/brand/bo-mark.svg', 'system/assets/brand/bo-mark.svg');
const ctx = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(root, 'site', 'site.config.js'), 'utf8'), ctx);
const SITE = ctx.window.SITE;
const pad = n => String(n).padStart(2, '0');
const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[c]));

const days = fs.readdirSync(path.join(root, 'days')).filter(d => /^\d{2}$/.test(d)).sort();
const posters = days.map(d => {
  const dir = path.join(root, 'days', d);
  if (!fs.existsSync(path.join(dir, 'meta.json'))) return null;
  const meta = JSON.parse(fs.readFileSync(path.join(dir, 'meta.json'), 'utf8'));
  const prompt = fs.readFileSync(path.join(dir, 'prompt.md'), 'utf8').trim();
  cp(`days/${d}/poster.jpg`, `posters/${d}/poster.jpg`); cp(`days/${d}/thumb.jpg`, `posters/${d}/thumb.jpg`);
  return { ...meta, prompt, thumb: `posters/${d}/thumb.jpg`, image: `posters/${d}/poster.jpg` };
}).filter(Boolean);

fs.mkdirSync(path.join(dist, 'data'), { recursive: true });
fs.writeFileSync(path.join(dist, 'data', 'posters.js'),
  '// Generated by scripts/build-wall.js. Do not edit by hand.\nwindow.POSTERS = ' + JSON.stringify(posters, null, 2) + ';\n');

// RSS, newest first
const items = posters.slice().sort((a, b) => b.day - a.day).map(p => {
  const link = `${SITE.url}#day-${pad(p.day)}`, img = SITE.url + p.image;
  const html = `<p><img src="${img}" alt="Day ${pad(p.day)} poster, ${esc(p.title)}" width="620"></p><p>${esc(p.note || '')}</p><p><strong>The prompt, as typed:</strong></p><blockquote>${esc(p.prompt)}</blockquote><p><a href="${link}">See it on the wall and copy the prompt</a></p>`;
  return `    <item>
      <title>Day ${pad(p.day)}: ${esc(p.title)}</title>
      <link>${link}</link>
      <guid isPermaLink="false">thirty-posters-day-${pad(p.day)}</guid>
      <pubDate>${new Date(p.date + 'T18:00:00Z').toUTCString()}</pubDate>
      <enclosure url="${img}" type="image/jpeg" length="${fs.statSync(path.join(dist, p.image)).size}"/>
      <description><![CDATA[${html}]]></description>
    </item>`;
}).join('\n');
fs.writeFileSync(path.join(dist, 'feed.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Thirty posters</title>
    <link>${SITE.url}</link>
    <atom:link href="${SITE.url}feed.xml" rel="self" type="application/rss+xml"/>
    <description>30 days, 30 posters, 60 seconds of prompting each. Made in Claude Code, posted as is.</description>
    <language>en-gb</language>
${items}
  </channel>
</rss>
`);

// Share preview: the latest poster, or nothing yet
const latest = posters.slice().sort((a, b) => b.day - a.day)[0];
const title = latest ? `Day ${pad(latest.day)}: ${latest.title} · Thirty posters` : 'Thirty posters';
const desc = '30 days, 30 posters, 60 seconds of prompting each. Every prompt free to copy.';
const og = [
  `<meta property="og:title" content="${esc(title)}">`,
  `<meta property="og:description" content="${esc(desc)}">`,
  `<meta property="og:url" content="${SITE.url}">`,
  `<meta property="og:type" content="website">`,
  latest ? `<meta property="og:image" content="${SITE.url}${latest.image}">` : '',
  `<meta name="twitter:card" content="summary_large_image">`
].filter(Boolean).join('\n');
const ip = path.join(dist, 'index.html');
fs.writeFileSync(ip, fs.readFileSync(ip, 'utf8').replace(/<!-- og:start -->[\s\S]*?<!-- og:end -->/, `<!-- og:start -->\n${og}\n<!-- og:end -->`));

console.log(`site built in dist/: ${posters.length} poster(s)`);
